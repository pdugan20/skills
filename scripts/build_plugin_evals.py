#!/usr/bin/env python3
"""Generate claude plugin eval cases from each skill's versioned eval files.

skills/<skill>/evals/evals.json and routing.json remain the reviewed source of
truth. This script translates them into the case layout that Claude Code's
claude plugin eval runner reads, one directory per case, inside an ignored
workspace directory. It never calls a model.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUTPUT = ROOT / "agent-skills-workspace" / "plugin-evals"
MARKER = ".generated-plugin-evals"
PRESERVED_ENTRIES = {MARKER, "results"}
FIXTURE_PREFIX = PurePosixPath("evals/fixtures")
SKILL_NAME_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
SAFE_PATH_RE = re.compile(r"^[A-Za-z0-9._/-]+$")
READ_ONLY_TOOLS = ["Read", "Glob", "Grep", "Skill"]
EXECUTION_LIMITS = {"max_turns": 20, "timeout_seconds": 600}
ROUTING_LIMITS = {"max_turns": 10, "timeout_seconds": 300}
LOADED_CASES_RE = re.compile(r"Ablation: \d+ arms? × (\d+) cases?")
LOAD_FAILURE_RE = re.compile(r"(\d+) case file\(s\) failed to load")

Scalar = str | int | bool
FieldValue = Scalar | list[str]


class ConversionError(Exception):
    """Raised when eval source files cannot be translated safely."""


@dataclass(frozen=True)
class GeneratedSkill:
    name: str
    execution_cases: int
    routing_cases: int


def yaml_scalar(value: Scalar) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    # A JSON string is a valid YAML double-quoted scalar.
    return json.dumps(value, ensure_ascii=False)


def yaml_value(value: FieldValue) -> str:
    if isinstance(value, list):
        return "[" + ", ".join(yaml_scalar(item) for item in value) + "]"
    return yaml_scalar(value)


def markdown_with_frontmatter(fields: dict[str, FieldValue], body: str = "") -> str:
    lines = ["---", *(f"{key}: {yaml_value(value)}" for key, value in fields.items()), "---"]
    text = "\n".join(lines) + "\n"
    if body:
        text += "\n" + body.rstrip("\n") + "\n"
    return text


def skill_invocation_pattern(skill: str) -> str:
    """Match a Skill tool input naming the skill, bare or plugin-namespaced."""
    return r'"skill"\s*:\s*"(?:[\w-]+:)?' + skill + '"'


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_json(path: Path) -> object:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise ConversionError(f"{path}: cannot read JSON ({error})") from error


def fixture_path(skill_dir: Path, item: str) -> tuple[Path, PurePosixPath]:
    """Return the source file and its path inside the run workspace."""
    relative = PurePosixPath(item)
    if (
        not SAFE_PATH_RE.fullmatch(item)
        or relative.is_absolute()
        or ".." in relative.parts
        or not relative.parts
    ):
        raise ConversionError(f"{skill_dir.name}: unsafe eval file path {item!r}")
    source = skill_dir / Path(*relative.parts)
    if not source.is_file():
        raise ConversionError(f"{skill_dir.name}: missing eval file {item!r}")
    # A symlinked fixture must not pull content from outside the skill.
    if not source.resolve().is_relative_to(skill_dir.resolve()):
        raise ConversionError(f"{skill_dir.name}: eval file {item!r} resolves outside the skill")
    if relative.is_relative_to(FIXTURE_PREFIX):
        relative = relative.relative_to(FIXTURE_PREFIX)
    return source, relative


def scaffold_script(files: list[tuple[Path, PurePosixPath]]) -> str:
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by scripts/build_plugin_evals.py; recreates this case's attached",
        "# files in the run workspace. Runs only with claude plugin eval --scaffold.",
        "set -euo pipefail",
    ]
    for index, (source, target) in enumerate(files, start=1):
        delimiter = f"EVAL_FILE_{index}"
        encoded = base64.encodebytes(source.read_bytes()).decode("ascii").rstrip("\n")
        if str(target.parent) != ".":
            lines.append(f"mkdir -p {shlex.quote(str(target.parent))}")
        lines.append(f"base64 --decode > {shlex.quote(str(target))} <<'{delimiter}'")
        lines.append(encoded)
        lines.append(delimiter)
        if source.stat().st_mode & 0o111:
            lines.append(f"chmod +x {shlex.quote(str(target))}")
    return "\n".join(lines) + "\n"


def write(path: Path, text: str, executable: bool = False) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    if executable:
        path.chmod(0o755)


def plugin_reference(case_dir: Path, plugin_root: Path) -> list[str]:
    return [Path(os.path.relpath(plugin_root, case_dir)).as_posix()]


def assertion_rubric(assertion: str) -> str:
    return (
        "Judge only the final response against this requirement from the skill's "
        "reviewed eval:\n\n"
        f"{assertion}\n\n"
        "PASS if the response clearly satisfies the requirement.\n"
        "FAIL if the response contradicts or omits it, or only restates it without "
        "applying it to the task."
    )


def generate_execution_cases(
    skill: str, skill_dir: Path, skill_out: Path, plugin_root: Path
) -> int:
    manifest = load_json(skill_dir / "evals" / "evals.json")
    if not isinstance(manifest, dict) or not isinstance(manifest.get("evals"), list):
        raise ConversionError(f"{skill}: evals.json must contain an evals array")
    cases = manifest["evals"]
    for case in cases:
        if not isinstance(case, dict):
            raise ConversionError(f"{skill}: every execution eval must be an object")
        case_id = case.get("id")
        prompt = case.get("prompt")
        assertions = case.get("assertions")
        if not isinstance(case_id, int) or isinstance(case_id, bool):
            raise ConversionError(f"{skill}: execution eval ids must be integers")
        if not isinstance(prompt, str) or not prompt.strip():
            raise ConversionError(f"{skill}: execution eval {case_id} needs a prompt")
        if not isinstance(assertions, list) or not assertions:
            raise ConversionError(f"{skill}: execution eval {case_id} needs assertions")

        case_dir = skill_out / f"execution-{case_id:02d}"
        name = f"{skill}-execution-{case_id:02d}"
        files = [fixture_path(skill_dir, item) for item in case.get("files", [])]
        tags = [skill, "execution"]
        extra_tags = case.get("tags", [])
        if not isinstance(extra_tags, list) or not all(isinstance(tag, str) for tag in extra_tags):
            raise ConversionError(f"{skill}: execution eval {case_id} tags must be strings")
        tags.extend(tag for tag in extra_tags if tag not in tags)
        body = prompt
        if files:
            tags.append("needs-scaffold")
            listing = "\n".join(f"- {target}" for _, target in files)
            body += f"\n\nAttached files (in the working directory):\n{listing}"
            write(case_dir / "scaffold.sh", scaffold_script(files), executable=True)
            write(
                case_dir / "case.yaml",
                "\n".join(
                    [
                        'schema_version: "1.1"',
                        f"name: {yaml_scalar(name)}",
                        "context:",
                        '  scaffold_script: "scaffold.sh"',
                    ]
                )
                + "\n",
            )

        fields: dict[str, FieldValue] = {
            "name": name,
            "description": f"Execution eval {case_id} for {skill}.",
            "tags": tags,
            "plugins": plugin_reference(case_dir, plugin_root),
            "allowed_tools": READ_ONLY_TOOLS,
            **EXECUTION_LIMITS,
        }
        expected = case.get("expected_output")
        if isinstance(expected, str) and expected.strip():
            fields["expected_outcome"] = expected
        write(case_dir / "prompt.md", markdown_with_frontmatter(fields, body))

        for index, assertion in enumerate(assertions, start=1):
            if not isinstance(assertion, str) or not assertion.strip():
                raise ConversionError(f"{skill}: execution eval {case_id} has an empty assertion")
            write(
                case_dir / "graders" / f"assertion-{index:02d}.md",
                markdown_with_frontmatter({"type": "llm"}, assertion_rubric(assertion)),
            )
        write(
            case_dir / "graders" / "skill-fired.md",
            markdown_with_frontmatter(
                {
                    "type": "tool_used",
                    "tool": "Skill",
                    "input_match": skill_invocation_pattern(skill),
                }
            ),
        )
    return len(cases)


def generate_routing_cases(
    skill: str, skill_dir: Path, skill_out: Path, plugin_root: Path
) -> int:
    routing = load_json(skill_dir / "evals" / "routing.json")
    if not isinstance(routing, list):
        raise ConversionError(f"{skill}: routing.json must be an array")
    for index, case in enumerate(routing, start=1):
        if not isinstance(case, dict):
            raise ConversionError(f"{skill}: every routing eval must be an object")
        query = case.get("query")
        should_trigger = case.get("should_trigger")
        if not isinstance(query, str) or not query.strip():
            raise ConversionError(f"{skill}: routing eval {index} needs a query")
        if not isinstance(should_trigger, bool):
            raise ConversionError(f"{skill}: routing eval {index} needs should_trigger")

        case_dir = skill_out / f"routing-{index:02d}"
        polarity = "positive" if should_trigger else "negative"
        expectation = "should" if should_trigger else "should not"
        fields: dict[str, FieldValue] = {
            "name": f"{skill}-routing-{index:02d}",
            "description": f"Routing eval: {skill} {expectation} trigger.",
            "tags": [skill, "routing", polarity, *(["held-out"] if case.get("held_out") is True else [])],
            "plugins": plugin_reference(case_dir, plugin_root),
            "allowed_tools": READ_ONLY_TOOLS,
            **ROUTING_LIMITS,
        }
        write(case_dir / "prompt.md", markdown_with_frontmatter(fields, query))

        grader: dict[str, FieldValue] = {
            "type": "tool_used",
            "tool": "Skill",
            "input_match": skill_invocation_pattern(skill),
        }
        if should_trigger:
            grader_name = "skill-fired"
        else:
            # A must-not-fire check stays meaningful in both arms of a two-arm run.
            grader_name = "skill-not-fired"
            grader.update({"min": 0, "max": 0, "arm": "both"})
        write(case_dir / "graders" / f"{grader_name}.md", markdown_with_frontmatter(grader))
    return len(routing)


def prepare_output(output: Path) -> None:
    """Clear earlier generated cases while keeping run results."""
    if output.exists():
        if not output.is_dir():
            raise ConversionError(f"{output} exists and is not a directory")
        entries = list(output.iterdir())
        if entries and not (output / MARKER).is_file():
            raise ConversionError(
                f"{output} is not empty and was not generated by this script; "
                "choose another --output"
            )
        for entry in entries:
            if entry.name in PRESERVED_ENTRIES:
                continue
            if entry.is_dir() and not entry.is_symlink():
                shutil.rmtree(entry)
            else:
                entry.unlink()
    output.mkdir(parents=True, exist_ok=True)
    write(
        output / MARKER,
        "Generated by scripts/build_plugin_evals.py. Regenerating replaces every\n"
        "entry here except results/.\n",
    )


def available_skills(skills_root: Path) -> list[str]:
    return sorted(
        path.name
        for path in skills_root.iterdir()
        if path.is_dir() and (path / "SKILL.md").is_file()
    )


def build(
    output: Path,
    *,
    root: Path = ROOT,
    skills: list[str] | None = None,
    kinds: tuple[str, ...] = ("execution", "routing"),
) -> list[GeneratedSkill]:
    skills_root = root / "skills"
    known = available_skills(skills_root)
    selected = sorted(set(skills)) if skills else known
    unknown = [name for name in selected if name not in known]
    if unknown:
        raise ConversionError(f"unknown skills: {', '.join(unknown)}")
    for name in selected:
        if not SKILL_NAME_RE.fullmatch(name):
            raise ConversionError(f"skill name {name!r} cannot be matched safely")

    prepare_output(output)
    generated: list[GeneratedSkill] = []
    sources: dict[str, dict[str, object]] = {}
    for name in selected:
        skill_dir = skills_root / name
        skill_out = output / name
        execution = (
            generate_execution_cases(name, skill_dir, skill_out, root)
            if "execution" in kinds
            else 0
        )
        routing = (
            generate_routing_cases(name, skill_dir, skill_out, root)
            if "routing" in kinds
            else 0
        )
        generated.append(GeneratedSkill(name, execution, routing))
        sources[name] = {
            "skill_md_sha256": sha256(skill_dir / "SKILL.md"),
            "evals_json_sha256": sha256(skill_dir / "evals" / "evals.json"),
            "routing_json_sha256": sha256(skill_dir / "evals" / "routing.json"),
            "execution_cases": execution,
            "routing_cases": routing,
        }
    write(
        output / "manifest.json",
        json.dumps(
            {"generator": "scripts/build_plugin_evals.py", "case_schema": "1.1", "skills": sources},
            indent=2,
        )
        + "\n",
    )
    return generated


def load_check_errors(output: str, expected_cases: int) -> list[str]:
    """Interpret a zero-cost claude plugin eval run; fail closed on unknown output.

    The runner's exit code is 2 whenever the cost ceiling stops it, even when some
    cases failed to load, and its JSON result has no load-error field, so the
    printed summary is the only signal.
    """
    errors: list[str] = []
    failures = LOAD_FAILURE_RE.search(output)
    if failures:
        errors.append(f"{failures.group(1)} generated case(s) failed to load")
    loaded = LOADED_CASES_RE.search(output)
    if loaded is None:
        errors.append("could not find the runner's loaded-case summary; its output format may have changed")
    elif int(loaded.group(1)) != expected_cases:
        errors.append(f"runner loaded {loaded.group(1)} cases, expected {expected_cases}")
    if "cost ceiling $0 hit" not in output:
        errors.append("runner did not stop at the $0 cost ceiling")
    return errors


def claude_executable(root: Path) -> str | None:
    local = root / "node_modules" / ".bin" / "claude"
    return str(local) if local.is_file() else shutil.which("claude")


def check_loading(output: Path, expected_cases: int, root: Path = ROOT) -> list[str]:
    """Ask the pinned Claude CLI to load every generated case without running any."""
    claude = claude_executable(root)
    if claude is None:
        return ["claude CLI not found; run npm ci first"]
    try:
        eval_dir = output.relative_to(root).as_posix()
    except ValueError:
        return [f"--check needs an --output inside {root}, because --eval-dir is relative to the plugin"]
    result = subprocess.run(
        [
            claude,
            "plugin",
            "eval",
            str(root),
            "--eval-dir",
            eval_dir,
            "--max-cost-usd",
            "0",
            "--no-publish",
            "--trust-plugin",
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    errors = load_check_errors(result.stdout + result.stderr, expected_cases)
    if result.returncode != 2:
        errors.append(f"runner exited {result.returncode}; a $0 ceiling should exit 2")
    if errors:
        print(result.stdout + result.stderr, file=sys.stderr)
    return errors


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--output",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="eval directory to write (default: agent-skills-workspace/plugin-evals)",
    )
    parser.add_argument(
        "--skill", action="append", dest="skills", help="limit to one skill; repeatable"
    )
    parser.add_argument(
        "--kind", choices=("all", "execution", "routing"), default="all"
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="also load every generated case in the pinned Claude CLI with a $0 cost ceiling",
    )
    args = parser.parse_args(argv)
    kinds = ("execution", "routing") if args.kind == "all" else (args.kind,)
    output = args.output.resolve()
    try:
        generated = build(output, skills=args.skills, kinds=kinds)
    except ConversionError as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1

    execution = sum(item.execution_cases for item in generated)
    routing = sum(item.routing_cases for item in generated)
    try:
        shown = output.relative_to(ROOT).as_posix()
    except ValueError:
        shown = str(output)
    print(
        f"Wrote {execution} execution and {routing} routing cases for "
        f"{len(generated)} skills to {shown}."
    )
    if args.check:
        errors = check_loading(output, execution + routing)
        if errors:
            for message in errors:
                print(f"ERROR: {message}", file=sys.stderr)
            return 1
        print("claude plugin eval loaded every generated case without running any.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
